@dataclass
class Ctx:
    root: Path
    home: Path
    command: str                     # executable for MCP configs
    args_prefix: list[str]           # e.g. ["-m", "promapkin"] when command is python
    dry_run: bool = False
    changes: list[dict[str, Any]] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def server_args(self, root_value: str) -> list[str]:
        return [*self.args_prefix, "--root", root_value, "mcp", "serve"]

    def cli(self, *args: str, root_value: str = "") -> str:
        parts = [self.command, *self.args_prefix, "--root", root_value or str(self.root), *args]
        return " ".join(_shell_quote(p) for p in parts)


@dataclass
class Platform:
    name: str
    title: str
    verified: str                    # high | medium | low (how sure the format is)
    install: Callable[[Ctx], None]
    scope: str = "project"           # project | user (where the MCP registration lives)
    aliases: tuple[str, ...] = ()


# ====================================================================== file operations
def _rel(ctx: Ctx, path: Path) -> str:
    try:
        return str(path.relative_to(ctx.root))
    except ValueError:
        return str(path).replace(str(ctx.home), "~", 1)


def _write(ctx: Ctx, path: Path, text: str) -> None:
    if ctx.dry_run:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def json_merge(ctx: Ctx, path: Path, keys: list[str], value: Any) -> None:
    """Set data[keys[0]]...[keys[-1]] = value, keeping everything else in the file."""
    existed = path.exists()
    data: dict[str, Any] = {}
    if existed:
        raw = path.read_text()
        try:
            data = json.loads(raw) if raw.strip() else {}
        except json.JSONDecodeError:
            ctx.notes.append(f"skipped {_rel(ctx, path)}: not valid JSON (comments?); add the promapkin server by hand")
            return
        if not isinstance(data, dict):
            ctx.notes.append(f"skipped {_rel(ctx, path)}: unexpected JSON shape")
            return
    node = data
    for k in keys[:-1]:
        if not isinstance(node.get(k), dict):
            node[k] = {}
        node = node[k]
    previous = node.get(keys[-1])
    if previous == value:
        ctx.changes.append({"op": "json", "path": str(path), "keys": keys, "status": "unchanged"})
        return
    node[keys[-1]] = value
    _write(ctx, path, json.dumps(data, indent=2) + "\n")
    ctx.changes.append({"op": "json", "path": str(path), "keys": keys, "created": not existed,
                        "previous": previous, "status": "updated" if existed else "created"})


def json_hooks(ctx: Ctx, path: Path, event: str, matcher: str | None, command: str, timeout: int,
               flat: bool = False) -> None:
    """Add one command hook (Claude Code / Codex / Crush shape: event -> [{matcher, hooks: [...]}]), idempotent."""
    existed = path.exists()
    data: dict[str, Any] = {}
    if existed:
        try:
            data = json.loads(path.read_text() or "{}")
        except json.JSONDecodeError:
            ctx.notes.append(f"skipped hooks in {_rel(ctx, path)}: not valid JSON")
            return
    before = json.dumps(data, sort_keys=True)
    hooks = data.setdefault("hooks", {})
    groups = hooks.setdefault(event, [])
    handler = {"type": "command", "command": command, "timeout": timeout}
    if flat:
        groups[:] = [g for g in groups if MARK not in json.dumps(g)]
        groups.append(handler)
    else:
        groups[:] = [g for g in groups if not (isinstance(g, dict) and MARK in json.dumps(g.get("hooks", [])))]
        group: dict[str, Any] = {"hooks": [handler]}
        if matcher:
            group = {"matcher": matcher, **group}
        groups.append(group)
    if json.dumps(data, sort_keys=True) == before:
        ctx.changes.append({"op": "hooks", "path": str(path), "event": event, "status": "unchanged"})
        return
    _write(ctx, path, json.dumps(data, indent=2) + "\n")
    ctx.changes.append({"op": "hooks", "path": str(path), "event": event, "created": not existed,
                        "status": "updated" if existed else "created"})


def text_block(ctx: Ctx, path: Path, body: str, start: str = MD_START, end: str = MD_END) -> None:
    """Insert or replace our marked block in a text file (CLAUDE.md, AGENTS.md, config.toml, ...)."""
    existed = path.exists()
    text = path.read_text() if existed else ""
    block = f"{start}\n{body.rstrip()}\n{end}\n"
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end) + r"\n?", re.S)
    if pattern.search(text):
        new = pattern.sub(lambda _m: block, text, count=1)
    else:
        new = (text.rstrip() + "\n\n" if text.strip() else "") + block
    if new == text:
        ctx.changes.append({"op": "block", "path": str(path), "status": "unchanged"})
        return
    _write(ctx, path, new)
    ctx.changes.append({"op": "block", "path": str(path), "start": start, "end": end, "created": not existed,
                        "status": "updated" if existed else "created"})


def owned_file(ctx: Ctx, path: Path, text: str) -> None:
    """A file Promapkin owns. Rewritten only while it still carries our marker and is unedited."""
    if path.exists():
        current = path.read_text()
        if OWNED not in current:
            ctx.notes.append(f"kept {_rel(ctx, path)}: it exists and was not created by promapkin")
            return
        if current == text:
            ctx.changes.append({"op": "file", "path": str(path), "status": "unchanged"})
            return
    _write(ctx, path, text)
    ctx.changes.append({"op": "file", "path": str(path), "status": "written"})


# ====================================================================== shared content
def _md_rules(frontmatter: str = "") -> str:
    head = f"---\n{frontmatter.strip()}\n---\n" if frontmatter else ""
    return f"{head}<!-- {OWNED}; edit freely, promapkin will then leave it alone. -->\n\n{INSTRUCTIONS}"


def _command_md(desc: str, body: str, frontmatter_extra: str = "") -> str:
    extra = f"\n{frontmatter_extra.strip()}" if frontmatter_extra else ""
    return f"---\ndescription: {desc}\nargument-hint: [task or symbol]{extra}\n---\n<!-- {OWNED} -->\n\n{body}\n"


def stdio_entry(ctx: Ctx, root_value: str, with_type: bool = False, **extra: Any) -> dict[str, Any]:
    entry: dict[str, Any] = {"type": "stdio"} if with_type else {}
    entry.update({"command": ctx.command, "args": ctx.server_args(root_value)})
    entry.update(extra)
    return entry


def agents_md(ctx: Ctx) -> None:
    text_block(ctx, ctx.root / "AGENTS.md", INSTRUCTIONS)


