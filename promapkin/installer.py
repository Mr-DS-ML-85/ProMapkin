MARK = "promapkin"
MD_START, MD_END = "<!-- promapkin:start -->", "<!-- promapkin:end -->"
HASH_START, HASH_END = "# >>> promapkin (managed block; `promapkin uninstall` removes it)", "# <<< promapkin"
OWNED = "Generated by `promapkin install`"

