def claude_code(ctx: Ctx) -> None:
    json_merge(ctx, ctx.root / ".mcp.json", ["mcpServers", "promapkin"],
               stdio_entry(ctx, "${CLAUDE_PROJECT_DIR:-.}", with_type=True))
    text_block(ctx, ctx.root / "CLAUDE.md", INSTRUCTIONS)
    settings = ctx.root / ".claude" / "settings.json"
    root_var = '"$CLAUDE_PROJECT_DIR"'
    json_hooks(ctx, settings, "SessionStart", "startup|resume|clear|compact",
               ctx.cli("brief", "--sync", root_value="__ROOT__").replace(_shell_quote("__ROOT__"), root_var), 60)
    json_hooks(ctx, settings, "PostToolUse", "Edit|MultiEdit|Write",
               ctx.cli("scan", root_value="__ROOT__").replace(_shell_quote("__ROOT__"), root_var) + " >/dev/null 2>&1",
               60)
    skill = ctx.root / ".claude" / "skills" / "promapkin" / "SKILL.md"
    owned_file(ctx, skill, "---\nname: promapkin\ndescription: Use the Promapkin codebase map (MCP server "
               "`promapkin`) for task context, change impact, tracing and handoffs before exploring files "
               f"manually.\n---\n<!-- {OWNED} -->\n\n{INSTRUCTIONS}")
    for name, (desc, body) in COMMANDS.items():
        owned_file(ctx, ctx.root / ".claude" / "commands" / f"promapkin-{name}.md", _command_md(desc, body))


