def resolve_platform(name: str) -> Platform:
    key = name.lower().strip()
    for p in PLATFORMS.values():
        if key == p.name or key in p.aliases:
            return p
    raise ValueError(f"unknown platform {name!r}; choose from: {', '.join(PLATFORMS)}")


