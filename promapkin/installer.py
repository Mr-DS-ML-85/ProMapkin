"""`promapkin install --platform <assistant>`: one command to wire Promapkin into a coding assistant.

For each platform this registers the MCP server in the file that assistant reads, adds a short instructions
block to its rules/instructions file, and, where the platform supports them, installs session-start hooks
(a factual orientation from `promapkin brief`), an index refresh after edits, and slash commands/skills.

Every change is merge-safe and reversible:
- JSON configs are parsed and only our entry is added or replaced; other servers and settings are kept.
  A file that is not valid JSON is never rewritten.
- Text files get a marked block (`promapkin:start` / `promapkin:end`) that is replaced in place.
- Files Promapkin owns entirely (commands, rules, skills) carry a marker line and are never overwritten
  once someone has edited them.
- What was changed is recorded in .promapkin/installs.json so `promapkin uninstall` can undo exactly that.

Formats follow each assistant's documentation as of late 2026; the `verified` level on each platform says how
sure we are, and `promapkin install --list` shows it.
"""

