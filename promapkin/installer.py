# ====================================================================== entry points
def make_ctx(root: Path, dry_run: bool = False, portable: bool = False, home: Path | None = None) -> Ctx:
    exe = shutil.which("promapkin")
    if portable or exe:
        command, prefix = ("promapkin" if portable else exe), []
    else:
        command, prefix = sys.executable, ["-m", "promapkin"]
    return Ctx(root=root.resolve(), home=(home or Path.home()), command=str(command), args_prefix=prefix,
               dry_run=dry_run)


def install(root: Path, platforms: list[str], dry_run: bool = False, portable: bool = False,
            home: Path | None = None) -> dict[str, Any]:
    ctx = make_ctx(root, dry_run, portable, home)
    done = []
    for name in platforms:
        p = resolve_platform(name)
        before = len(ctx.changes)
        p.install(ctx)
        for c in ctx.changes[before:]:
            c["platform"] = p.name
        done.append({"platform": p.name, "title": p.title, "verified": p.verified, "scope": p.scope})
    if not dry_run:
        _record(ctx, [c for c in ctx.changes if c["status"] != "unchanged"])
    return {"platforms": done, "dry_run": dry_run, "command": " ".join([ctx.command, *ctx.args_prefix]),
            "changes": [{**c, "path": _rel(ctx, Path(c["path"]))} for c in ctx.changes
                        if c["status"] != "unchanged"],
            "unchanged": sum(1 for c in ctx.changes if c["status"] == "unchanged"), "notes": ctx.notes}


def uninstall(root: Path, platforms: list[str] | None = None, home: Path | None = None) -> dict[str, Any]:
    root = root.resolve()
    ledger = _ledger_path(root)
    records = json.loads(ledger.read_text()) if ledger.exists() else []
    wanted = {resolve_platform(p).name for p in platforms} if platforms else None
    keep, removed, notes = [], [], []
    for rec in reversed(records):   # newest first, so a file we created is deleted only once it is empty again
        if wanted is not None and rec.get("platform") not in wanted:
            keep.append(rec)
            continue
        path = Path(rec["path"])
        try:
            outcome = _undo(rec, path)
        except (OSError, json.JSONDecodeError) as exc:
            notes.append(f"could not undo {path}: {exc}")
            keep.append(rec)
            continue
        if outcome:
            removed.append({"platform": rec.get("platform"), "path": str(path), "action": outcome})
    if ledger.exists():
        ledger.write_text(json.dumps(keep[::-1], indent=2) + "\n") if keep else ledger.unlink()
    return {"removed": removed, "notes": notes}


def _undo(rec: dict[str, Any], path: Path) -> str | None:
    if not path.exists():
        return None
    op = rec["op"]
    if op == "file":
        if OWNED in path.read_text():
            path.unlink()
            _prune_dirs(path.parent)
            return "deleted"
        return None
    if op == "block":
        text = path.read_text()
        pattern = re.compile(r"\n*" + re.escape(rec["start"]) + r".*?" + re.escape(rec["end"]) + r"\n?", re.S)
        new = pattern.sub("\n", text).strip("\n")
        if rec.get("created") and not new.strip():
            path.unlink()
            _prune_dirs(path.parent)
            return "deleted"
        path.write_text(new + "\n" if new else "")
        return "block removed"
    data = json.loads(path.read_text() or "{}")
    if op == "json":
        node = data
        for k in rec["keys"][:-1]:
            node = node.get(k, {})
        if rec.get("previous") is not None:
            node[rec["keys"][-1]] = rec["previous"]
        else:
            node.pop(rec["keys"][-1], None)
        _drop_empty(data, rec["keys"][:-1])
    elif op == "hooks":
        groups = data.get("hooks", {}).get(rec["event"], [])
        groups[:] = [g for g in groups if MARK not in json.dumps(g)]
        if not groups:
            data.get("hooks", {}).pop(rec["event"], None)
        if not data.get("hooks"):
            data.pop("hooks", None)
    if rec.get("created") and (not data or set(data) <= {"$schema"}):
        path.unlink()
        _prune_dirs(path.parent)
        return "deleted"
    path.write_text(json.dumps(data, indent=2) + "\n")
    return "entry removed"


def _drop_empty(data: dict[str, Any], keys: list[str]) -> None:
    for depth in range(len(keys), 0, -1):
        node = data
        for k in keys[:depth - 1]:
            node = node.get(k, {})
        if isinstance(node.get(keys[depth - 1]), dict) and not node[keys[depth - 1]]:
            node.pop(keys[depth - 1])


def _prune_dirs(d: Path) -> None:
    for _ in range(3):
        try:
            d.rmdir()   # only succeeds when empty
        except OSError:
            return
        d = d.parent


def _ledger_path(root: Path) -> Path:
    return root / ".promapkin" / "installs.json"


def _record(ctx: Ctx, changes: list[dict[str, Any]]) -> None:
    ledger = _ledger_path(ctx.root)
    ledger.parent.mkdir(exist_ok=True)
    records = json.loads(ledger.read_text()) if ledger.exists() else []
    seen = {(r["path"], r["op"], json.dumps(r.get("keys")), r.get("event")) for r in records}
    for c in changes:
        key = (c["path"], c["op"], json.dumps(c.get("keys")), c.get("event"))
        if key not in seen:
            records.append({**c, "installed_at": time.time()})
            seen.add(key)
    ledger.write_text(json.dumps(records, indent=2, default=str) + "\n")


def _seed_json(ctx: Ctx, path: Path, data: dict[str, Any]) -> None:
    _write(ctx, path, json.dumps(data, indent=2) + "\n")
    ctx.changes.append({"op": "json", "path": str(path), "keys": ["$schema"], "created": True, "previous": None,
                        "status": "created"})


def _yaml_extension(ctx: Ctx, path: Path, text: str, block: str) -> None:
    """Insert our extension right under the top-level `extensions:` key, as a marked block."""
    if HASH_START in text:
        text = re.sub(re.escape(HASH_START) + r".*?" + re.escape(HASH_END) + r"\n?", "", text, flags=re.S)
    new = re.sub(r"^(extensions:\s*\n)", lambda m: f"{m.group(1)}{HASH_START}\n{block}\n{HASH_END}\n", text,
                 count=1, flags=re.M)
    _write(ctx, path, new)
    ctx.changes.append({"op": "block", "path": str(path), "start": HASH_START, "end": HASH_END, "created": False,
                        "status": "updated"})


def _shell_quote(s: str) -> str:
    return s if re.fullmatch(r"[\w@%+=:,./${}-]+", s) else "'" + s.replace("'", "'\"'\"'") + "'"
